-- V3: rules become data.
--
-- Until now the rules were Java code (StarterRules), and changing one meant a code change,
-- a pull request and a restart. From here on every version of the rule set is a row in
-- rule_set, its rules stored as JSON in the format RuleSetJson describes. The app loads the
-- live version at startup, and from Sprint 2's publish step it swaps in a new version while
-- running, with no restart.
--
-- Versions 1 and 2 are copied in below exactly as they were written in StarterRules (the
-- JSON was produced by RuleSetJson itself, and RuleSetSeedIntegrationTest checks that it
-- still matches). So every decision already in decision_log can be explained by the exact
-- rules that made it.
--
-- Never edit this file once it has run anywhere. Add V4__..., V5__... instead.

create table rule_set (
    -- The number every decision records in decision_log.rule_set_version. Drafts get their
    -- number when they are created, so a draft, its approval and the decisions it makes all
    -- share one number. New rows are numbered from 3, because 1 and 2 are inserted below.
    version           integer       generated by default as identity (start with 3) primary key,
    status            varchar(16)   not null
                                    check (status in ('DRAFT', 'PENDING', 'PUBLISHED', 'REJECTED', 'DISCARDED')),
    based_on          integer       references rule_set (version),  -- the published version this one changes
    title             varchar(120)  not null,                       -- one line: what this version changes
    definition        jsonb         not null,                       -- the rules (format: RuleSetJson)
    revision          integer       not null,                       -- goes up by 1 on every save of a draft
    created_by        varchar(64)   not null,                       -- username of the author, the "maker"
    created_by_name   varchar(128)  not null,                       -- their display name at the time
    created_at        timestamptz   not null,
    updated_at        timestamptz   not null,
    submitted_at      timestamptz,                                  -- sent for approval
    reviewed_by       varchar(64),                                  -- the admin who approved or rejected it, the "checker"
    reviewed_by_name  varchar(128),
    reviewed_at       timestamptz,
    review_note       varchar(500)
);

-- Which version is live, and every time that changed. The newest row is the live version.
-- Rows are only ever added, never changed, so this is also the full history of publishes
-- and rollbacks: a rollback is a new row pointing at an older version.
create table rule_set_activation (
    id                 bigint        generated always as identity primary key,
    version            integer       not null references rule_set (version),
    kind               varchar(16)   not null check (kind in ('SEED', 'PUBLISH', 'ROLLBACK')),
    activated_by       varchar(64)   not null,
    activated_by_name  varchar(128)  not null,
    activated_at       timestamptz   not null
);

