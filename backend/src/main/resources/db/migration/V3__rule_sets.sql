-- Every decision names the rule set that made it. Make the database guarantee that the
-- version really exists. NOT VALID means "enforce this for every new row, but do not scan the
-- rows already there": existing decisions only use versions 1 and 2, which are inserted above,
-- and skipping the scan keeps this migration instant however big decision_log has grown.
alter table decision_log
    add constraint fk_decision_log_rule_set foreign key (rule_set_version) references rule_set (version) not valid;
